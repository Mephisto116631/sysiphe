-- Module Course (GPS) — v2.18.0, version sysiphe-course.apk.
--
-- Une ligne par course enregistrée. Même règle d'accès que perfs : un appareil
-- ne voit que les courses des profils auxquels il est rattaché. Comme perfs,
-- pas de lien au profil : les courses restent si un profil est supprimé.
-- client_id (créé sur le téléphone) : une course envoyée deux fois (réseau
-- coupé pendant la réponse) n'est enregistrée qu'une fois.
-- Additive : rien n'est modifié dans les tables existantes.
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists public.courses (
    id             bigint generated by default as identity primary key,
    user_id        uuid        not null,
    client_id      uuid        unique,
    debut          timestamptz not null,
    date           date        not null,
    distance_m     integer     not null default 0,
    duree_s        integer     not null default 0,   -- en mouvement
    duree_totale_s integer     not null default 0,   -- pauses comprises
    denivele_m     integer     not null default 0,
    splits_s       jsonb       not null default '[]', -- temps de chaque km
    trace          jsonb       not null default '[]', -- [[lat, lng, m, s], …]
    objectif       jsonb
);

create index if not exists courses_user_date on public.courses (user_id, date desc);

revoke all on public.courses from anon;
alter table public.courses enable row level security;
drop policy if exists courses_membres on public.courses;
create policy courses_membres on public.courses for all to authenticated
  using (public.is_profile_member(user_id))
  with check (public.is_profile_member(user_id));
revoke truncate, trigger, references on public.courses from authenticated;
grant select, insert, update, delete on public.courses to authenticated;
